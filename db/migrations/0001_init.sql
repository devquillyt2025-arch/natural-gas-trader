-- NatGas Trader on Neon (plain Postgres): the bus between the engine and the web app.
-- The engine connects as the database owner. The web app connects as natgas_web, which may read what the
-- dashboard shows and queue a command, and nothing else. Safe to run more than once.
--   npm run db:setup     applies this and gives natgas_web a password

-- ---------------------------------------------------------------- tables
create table if not exists public.decisions (
  id           bigint primary key,           -- engine-generated, so retries are idempotent
  ts           timestamptz not null,
  price        double precision,
  action       text not null,
  lots         integer,
  stop_loss    double precision,
  target       double precision,
  confidence   double precision,
  reasoning    text not null default '',
  approved     boolean not null,
  verdict_code text not null,
  verdict      text not null default '',
  snapshot     jsonb,                        -- exactly what was sent to the model
  mode         text not null check (mode in ('paper', 'live'))
);
create index if not exists decisions_mode_ts on public.decisions (mode, ts desc);

create table if not exists public.trades (
  id          text primary key,
  opened_at   timestamptz not null,
  closed_at   timestamptz not null,
  side        text not null check (side in ('LONG', 'SHORT')),
  lots        integer not null,
  qty         integer not null,              -- mmBtu
  entry       double precision not null,
  exit        double precision not null,
  pnl         double precision not null,     -- INR, net of costs
  r_multiple  double precision,
  exit_reason text not null,
  reasoning   text not null default '',
  decision_id bigint,                        -- no FK: rows may arrive in either order
  mode        text not null check (mode in ('paper', 'live'))
);
create index if not exists trades_mode_closed on public.trades (mode, closed_at desc);

create table if not exists public.candles (
  tf text not null check (tf in ('15m', '1d')),
  ts timestamptz not null,
  o  double precision not null,
  h  double precision not null,
  l  double precision not null,
  c  double precision not null,
  v  double precision not null default 0,
  primary key (tf, ts)
);

create table if not exists public.state (
  key        text primary key,
  value      jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.commands (
  id      bigint generated by default as identity primary key,
  ts      timestamptz not null default now(),
  type    text not null check (type in ('kill', 'resume', 'flatten', 'update_limits', 'upstox_code')),
  payload jsonb not null default '{}'::jsonb check (pg_column_size(payload) < 4096),
  status  text not null default 'pending' check (status in ('pending', 'acked', 'failed')),
  result  text
);
create index if not exists commands_pending on public.commands (id) where status = 'pending';

create table if not exists public.events (
  id    bigint primary key,
  ts    timestamptz not null,
  level text not null check (level in ('info', 'warn', 'error', 'trade')),
  msg   text not null
);
create index if not exists events_ts on public.events (ts desc);

-- Sign-in attempts to the web app, so its password cannot be guessed quickly.
create table if not exists public.login_attempts (
  id bigint generated always as identity primary key,
  ts timestamptz not null default now(),
  ip text not null
);
create index if not exists login_attempts_ts on public.login_attempts (ts);

-- Days on which the engine recorded decisions (the go-live checklist counts paper days).
create or replace view public.decision_days as
  select mode, (ts at time zone 'Asia/Kolkata')::date as day, count(*)::integer as decisions
  from public.decisions
  group by 1, 2;

-- ---------------------------------------------------------------- the web app's login
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'natgas_web') then
    create role natgas_web nologin;   -- scripts/setup-db.mjs gives it a password
  end if;
end $$;

revoke all on all tables in schema public from natgas_web;
grant usage on schema public to natgas_web;
grant select on public.decisions, public.trades, public.candles, public.state,
  public.commands, public.events, public.decision_days to natgas_web;
-- The only trading-related write: a new command. id, ts, status and result use their defaults.
grant insert (type, payload) on public.commands to natgas_web;
grant select, insert, delete on public.login_attempts to natgas_web;
